import { mkdirSync, writeFileSync, lstatSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { VERSION, sha256 } from './kit.mjs';

export function syntheticGLB(skinned = true) {
  const names = ['Hips', 'Spine', 'Head', 'LeftHand', 'RightHand', 'LeftFoot', 'RightFoot'];
  const bin = Buffer.alloc(skinned ? 108 : 36);
  [0, 0, 0, 1, 0, 0, 0, 1, 0].forEach((v, i) => bin.writeFloatLE(v, i * 4));
  if (skinned) for (let i = 0; i < 3; i++) bin.writeFloatLE(1, 60 + i * 16);
  const doc = { asset: { version: '2.0', generator: 'SYNTHETIC TEST TRIANGLE; NOT ART' }, scene: 0,
    scenes: [{ nodes: skinned ? [0, 7] : [0] }],
    nodes: skinned ? [...names.map((name, i) => ({ name, ...(i === 0 ? { children: [1, 2, 3, 4, 5, 6] } : {}) })), { mesh: 0, skin: 0 }] : [{ mesh: 0 }],
    meshes: [{ primitives: [{ attributes: skinned ? { POSITION: 0, JOINTS_0: 1, WEIGHTS_0: 2 } : { POSITION: 0 } }] }],
    buffers: [{ byteLength: bin.length }], bufferViews: [{ buffer: 0, byteOffset: 0, byteLength: 36 }],
    accessors: [{ bufferView: 0, componentType: 5126, count: 3, type: 'VEC3', min: [0, 0, 0], max: [1, 1, 0] }] };
  if (skinned) {
    doc.skins = [{ joints: names.map((_, i) => i) }];
    doc.bufferViews.push({ buffer: 0, byteOffset: 36, byteLength: 24 }, { buffer: 0, byteOffset: 60, byteLength: 48 });
    doc.accessors.push({ bufferView: 1, componentType: 5123, count: 3, type: 'VEC4' }, { bufferView: 2, componentType: 5126, count: 3, type: 'VEC4' });
  }
  const json = Buffer.from(JSON.stringify(doc)), padded = Buffer.alloc(Math.ceil(json.length / 4) * 4, 0x20); json.copy(padded);
  const header = Buffer.alloc(20); header.writeUInt32LE(0x46546c67, 0); header.writeUInt32LE(2, 4);
  header.writeUInt32LE(28 + padded.length + bin.length, 8); header.writeUInt32LE(padded.length, 12); header.writeUInt32LE(0x4e4f534a, 16);
  const binHeader = Buffer.alloc(8); binHeader.writeUInt32LE(bin.length, 0); binHeader.writeUInt32LE(0x004e4942, 4);
  return Buffer.concat([header, padded, binHeader, bin]);
}
export function createExample(directory) {
  mkdirSync(directory, { recursive: true });
  for (const file of ['body.glb', 'glasses.glb', 'SOURCE.md', 'package.json'])
    if (lstatSync(join(directory, file), { throwIfNoEntry: false })) throw new Error(`refusing to overwrite ${file}`);
  const body = syntheticGLB(), rigid = syntheticGLB(false);
  writeFileSync(join(directory, 'body.glb'), body, { flag: 'wx' }); writeFileSync(join(directory, 'glasses.glb'), rigid, { flag: 'wx' });
  writeFileSync(join(directory, 'SOURCE.md'), '# Synthetic fixture\nTriangles generated by example.mjs. No human rig or wearable fit is represented. Test data only.\n', { flag: 'wx' });
  const asset = (path, bytes) => ({ path, sha256: sha256(bytes), provenance: { author: 'CORO SOLTO test generator', source: 'tools/character-kit/example.mjs', license: 'synthetic-test-only', evidence: 'SOURCE.md' } });
  const identity = { rigId: 'synthetic-humanoid', rigRevision: 1, restPoseSha256: sha256('synthetic-rest-declaration'), bodyFamily: 'synthetic-family', fitProfile: 'synthetic-fit' };
  const socket = { bone: 'Head', position: [0, 0, 0], rotation: [0, 0, 0, 1], scale: [1, 1, 1] };
  const pkg = { schemaVersion: VERSION, status: 'draft', packageId: 'synthetic-example',
    rig: { id: identity.rigId, revision: 1, restPoseSha256: identity.restPoseSha256, units: 'meters', up: '+Y', forward: '+Z',
      bones: { hips: 'Hips', spine: 'Spine', head: 'Head', handLeft: 'LeftHand', handRight: 'RightHand', footLeft: 'LeftFoot', footRight: 'RightFoot' }, sockets: { face: socket, head: structuredClone(socket) } },
    body: { id: 'synthetic-body', family: identity.bodyFamily, fitProfile: identity.fitProfile, asset: asset('body.glb', body) },
    items: [{ id: 'test-glasses', catalogId: 'draft-test-glasses', slot: 'eyewear', kind: 'rigid', ...identity, socket: 'face', layer: 10, hideBodyRegions: [], excludes: [], asset: asset('glasses.glb', rigid) },
      { id: 'test-shirt', catalogId: 'draft-test-shirt', slot: 'shirt', kind: 'skinned', ...identity, socket: null, layer: 10, hideBodyRegions: ['torso'], excludes: [], asset: asset('body.glb', body) }] };
  writeFileSync(join(directory, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`, { flag: 'wx' });
  return pkg;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { if (!process.argv[2]) throw new Error('usage: example.mjs NEW_DIRECTORY'); createExample(resolve(process.argv[2])); }
  catch (e) { console.error(e.message); process.exitCode = 1; }
}
